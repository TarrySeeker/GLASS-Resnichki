import Image from 'next/image'
import { CONTENT } from '@/lib/content'
import type { Locale } from '@/lib/i18n'

/**
 * Первый экран: белая плоскость слева, кадр справа, резкая граница посередине.
 *
 * Приём — сам край. Кадр обрезан по нему так, что модель выглядывает из-за
 * плоскости: её волосы и плечо уходят за границу, а лицо и коробка остаются
 * в кадре целиком. Никакого растворения и никакой плитки под снимком —
 * граница обязана быть резкой, иначе угла, из-за которого выглядывают,
 * не остаётся.
 *
 * Текст лежит на той же плоскости, без подложки и рамки, и потому не
 * читается отдельной колонкой.
 *
 * Кадр один. Смена трёх снимков, стоявшая здесь до этого, спорила с приёмом:
 * указатели требовали места на плоскости, а вторая и третья модели сбивали
 * композицию, собранную под конкретный снимок. Три портрета остались полосой
 * ниже — там они и работают.
 *
 * Экран помещается без прокрутки: высота ровно 100dvh минус промо-полоса и
 * шапка. Обе вынесены в токены, чтобы высота не разъехалась при правке любой
 * из них.
 *
 * Раскладка по модульной сетке: семь колонок под текст, пять под кадр.
 * Текст живёт в границах поля, кадр уходит в край экрана.
 *
 * Пять колонок — это не про текст, а про масштаб модели. При `cover` масштаб
 * равен отношению ширины полосы к ширине кадра, и другого рычага у него нет:
 * 600 / 960 = 0.625 — ровно тот масштаб, что в макете. Семь колонок дали бы
 * 0.875, лицо распирало бы полосу, а низ коробки уходил за край. Заодно
 * широкая текстовая колонка позволяет поднять кегль заголовка до макетного.
 *
 * При фиксированной высоте пропорции полосы зависят от окна, а кадр всегда
 * 0.828 — совпасть они не могут, и `cover` что-то обрежет. Что именно,
 * решает точка привязки: кадр прижат правым нижним углом, поэтому низ
 * коробки стоит на одной высоте при любом окне, а срез уходит на волосы и на
 * левый край. Подробности — в комментарии к .hero-crop.
 *
 * На телефоне порядок обратный: сначала кадр с продуктом, под ним заголовок
 * и действие. Первое, что видит человек с телефона, — лицо и упаковка, а не
 * строка текста.
 *
 * Адаптация по трём ступеням: до 640 — кадр вертикальный 7:8, дальше 4:3,
 * с 1024 — раскладка в две колонки. Ниже 1024 делить экран нельзя: заголовку
 * остаётся 460 px, и «ВЛЮБЛЯЕТ» в них не встаёт.
 *
 * Кадр — hero-product.jpg, обрезанный по низу товара вариант общего снимка
 * product-hand.jpg. Обрезка не косметическая: она задаёт точку привязки, без
 * которой низ коробки гуляет по высоте от окна к окну.
 *
 * Появления у первого экрана нет намеренно: он и есть первое, что видит
 * человек, и любое раскрытие здесь читается задержкой загрузки, а не приёмом.
 */
export function Hero({ lang }: { lang: Locale }) {
  const t = CONTENT[lang]
  const [l1, l2] = t.home.heroLine.split('\n')

  const faces = [
    { src: '/media/hero-portrait.jpg', w: 1340, h: 2000 },
    { src: '/media/editorial-1.jpg', w: 1124, h: 2000 },
    { src: '/media/editorial-2.jpg', w: 1116, h: 2000 },
  ]

  return (
    <>
      <section className="hero-grid flex flex-col overflow-hidden lg:grid lg:h-[var(--hero-h)] lg:grid-cols-12 lg:grid-rows-[1fr_auto_1fr]">
        <div className="hero-text order-2 flex flex-col ps-[var(--gutter)] pe-[var(--gutter)] lg:order-1 lg:col-span-6 lg:row-start-2">
          <h1 className="t-hero t-hero--split">
            {l1}
            <br />
            {l2}
          </h1>
          <p className="t-lead t-muted mt-6 lg:mt-10">{t.home.heroNote}</p>
          {/* Действие ведёт не в каталог, а в блок образов ниже: там
              покупательница выбирает эффект, а не перебирает артикулы. */}
          <a href="#looks" className="btn btn-wide mt-6 self-start lg:mt-8 whitespace-nowrap">
            {t.home.heroCta}
          </a>
        </div>

        <div className="order-1 lg:relative lg:order-2 lg:col-span-6 lg:row-start-2 lg:row-end-4">
          <div className="hero-frame relative aspect-[7/8] overflow-hidden sm:aspect-[4/3]">
            <Image
              src="/media/hero-product.jpg"
              alt=""
              width={960}
              height={1160}
              loading="eager"
              fetchPriority="high"
              sizes="(max-width: 1024px) 100vw, 60vw"
              /* Прибит к рамке абсолютом: при h-full высота бралась от
                 собственных пропорций кадра, и он вылезал за полосу на 34 px,
                 а контейнер молча его обрезал — масштаб переставал совпадать
                 с расчётным. */
              className="hero-crop absolute inset-0 h-full w-full object-cover"
            />
          </div>
        </div>
      </section>

      {/* Три портрета в ряд — отдельный блок, а не продолжение первого экрана.
          Линия сверху нужна именно поэтому: без неё кадр первого экрана
          упирался нижней кромкой прямо в первый портрет, две фотографии
          склеивались в одну колонку и граница блоков пропадала.

          На 390 остаётся один портрет: три кадра шириной по 130 px
          превратились бы в марки. */}
      <div className="shots grid grid-cols-1 gap-px border-t border-[var(--color-rule)] sm:grid-cols-3">
        {faces.map((f, n) => (
          <div
            key={f.src}
            className={`tile tile-zoom rise aspect-[3/4] ${n > 0 ? 'hidden sm:block' : ''}`}
            data-rise-delay={`${n * 180}ms`}
          >
            <Image
              src={f.src}
              alt=""
              width={f.w}
              height={f.h}
              sizes="(max-width: 640px) 100vw, 33vw"
              style={{ objectPosition: '50% 22%' }}
            />
          </div>
        ))}
      </div>
    </>
  )
}
