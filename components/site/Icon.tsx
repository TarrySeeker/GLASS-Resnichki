/**
 * Знаки шапки и футера.
 *
 * До этого на витрине не было ни одной иконки: правый угол шапки читался
 * словами — ПОИСК, КАБИНЕТ, ИЗБРАННОЕ, КОРЗИНА. Слова несли характер, но
 * стоили 250 px, и из-за них избранное пряталось до 640, а язык с валютой —
 * до 1280. Знаки возвращают и то и другое на место.
 *
 * Рисунок подчинён тому, чем витрина уже написана. Линии на ней ровно в один
 * пиксель: линейки блоков, стрелки раскрытия, крестик снятого фильтра, сердце
 * на карточке товара. Знаки набраны той же линией — сетка 24, обводка 1.2,
 * при отрисовке в 20 px это ровно пиксель. Углы срезаны прямо, а не скруглены:
 * скруглённая обводка — почерк иконочных библиотек, и рядом с тонкой антиквой
 * логотипа она читается как чужая вставка.
 *
 * Сердце не рисуется заново — оно взято из карточки товара до последней
 * координаты. Один и тот же предмет на витрине и в шапке обязан быть одним и
 * тем же рисунком, иначе это два разных сердца.
 *
 * Знаки без подписей: у каждого элемента управления остаётся имя для чтения с
 * экрана, а в мобильном меню все четыре названы словами. Всплывающей подсказки
 * нет намеренно — системная жёлтая плашка сюда не подходит.
 */
type Props = {
  /** Сторона квадрата в пикселях. Обводка пересчитывается, линия остаётся в пиксель. */
  size?: number
}

function Glyph({ size = 20, children }: Props & { children: React.ReactNode }) {
  return (
    <svg
      viewBox="0 0 24 24"
      width={size}
      height={size}
      aria-hidden="true"
      focusable="false"
      fill="none"
      stroke="currentColor"
      strokeWidth={(1.2 * 20) / size}
      className="block"
    >
      {children}
    </svg>
  )
}

/** Поиск: линза и короткий хвост. */
export function IconSearch(p: Props) {
  return (
    <Glyph {...p}>
      <circle cx="10.5" cy="10.5" r="6.5" />
      <path d="M15.4 15.4 20.5 20.5" />
    </Glyph>
  )
}

