/**
 * Избранное. Тот же контур, что у сердца на карточке товара.
 *
 * Заливка сюда не пришла, хотя напрашивалась: залитое сердце среди трёх
 * контурных знаков весит вчетверо больше них и разваливает ровный ряд. О том,
 * что в списке что-то есть, говорит цифра рядом — она и появляется только
 * тогда. На карточке товара сердце заливается: там оно одно и отвечает за
 * состояние в одиночку.
 */
export function IconHeart(p: Props) {
  return (
    <Glyph {...p}>
      <path d="M12 20.5 4.6 13a4.6 4.6 0 0 1 6.5-6.5l.9.9.9-.9A4.6 4.6 0 0 1 19.4 13Z" />
    </Glyph>
  )
}

/**
 * Корзина: сумка, а не тележка. Тележка — знак супермаркета и большого чека;
 * здесь покупают одну коробку, и сумка ближе к тому, с чем отсюда уходят.
 */
export function IconBag(p: Props) {
  return (
    <Glyph {...p}>
      {/* Бока прямые, а не расширяющиеся книзу: развал читался ведром, а
          прямой прямоугольник ложится в тот же угольный почерк, что срезанные
          концы линий. Высота подогнана к соседям по кадру — иначе знак при
          равном квадрате выглядит мельче их. */}
      <path d="M4.5 8h15v12.5h-15z" />
      <path d="M8.9 8V6.6a3.1 3.1 0 0 1 6.2 0V8" />
    </Glyph>
  )
}

